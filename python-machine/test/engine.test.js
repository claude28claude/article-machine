  const t0 = Date.now();
  const { call, py } = await makeEngine();
  console.log("boot ms", Date.now() - t0, py.runPython("import sys; sys.version"));
  show("hello", await call("run", { code: 'print("Hello, World!")\nx = 5\nname = "Aman"' }));
