// End-to-end run with the mocked viewer runtime.
const { chromium } = require("./pw");
const path = require("path");
const fs = require("fs");
const PM = path.join(__dirname, "..");
const fontCss = fs.readFileSync(path.join(__dirname, "fonts/fonts.css"), "utf8");
const mock = fs.readFileSync(path.join(__dirname, "mock-claude.js"), "utf8");
(async () => {
  const base = process.argv[2];
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: "dark" });
  await context.addInitScript(mock);
  await context.route("https://cdn.jsdelivr.net/npm/codemirror@5.65.16/**", (r) => r.fulfill({ path: path.join(PM, "vendor/codemirror", r.request().url().split("codemirror@5.65.16/")[1]), contentType: "application/javascript" }));
  await context.route("https://fonts.googleapis.com/**", (r) => r.fulfill({ body: fontCss, contentType: "text/css" }));
  await context.route("https://fonts.gstatic.com/**", (r) => r.fulfill({ path: path.join(__dirname, "fonts", r.request().url().replace("https://fonts.gstatic.com/", "").replace(/\//g, "_")), contentType: "font/woff2" }));
  const page = await context.newPage();
  const logs = [];
  page.on("console", (m) => { if (m.type() === "error") logs.push("console: " + m.text()); });
  page.on("pageerror", (e) => logs.push("pageerror: " + e.message));
  const step = (s) => console.log("•", s);
  await page.goto(base + "index.html#today");
  await page.waitForFunction(() => /Python 3/.test(document.querySelector("#engine").textContent), null, { timeout: 60000 });
  await page.waitForTimeout(400);
  step("greeting: " + (await page.textContent(".page-title")));
  await page.goto(base + "index.html#l-1.1");
  await page.waitForTimeout(500);
  await page.evaluate(() => document.querySelector(".CodeMirror").CodeMirror.setValue('print("Hello, Python)'));
  await page.click('[data-act="run"]');
  await page.waitForSelector(".explain", { timeout: 20000 });
  await page.click('[data-act="t-error"]');
  await page.waitForFunction(() => /closing quote/.test(document.querySelector("#b-tutor-out").textContent), null, { timeout: 10000 });
  step("tutor explained error: " + (await page.textContent("#b-tutor-out")).replace(/\s+/g, " ").slice(0, 90));
  await page.screenshot({ path: path.join(PM, "shots/11-tutor.png") });
  await page.evaluate(() => document.querySelector(".CodeMirror").CodeMirror.setValue('print("Hello, Python!")'));
  await page.click('[data-act="check"]');
  await page.waitForSelector(".passed-banner", { timeout: 20000 });
  await page.waitForTimeout(1600);
  let doc = await page.evaluate(() => JSON.parse(JSON.stringify(window.__mockDocs.get("data/users/u_test/progress") || null)));
  step("db after pass: ex=" + JSON.stringify(doc && doc.ex) + " xp=" + (doc && doc.xp));
  const code = await page.evaluate(() => JSON.parse(JSON.stringify(window.__mockDocs.get("data/users/u_test/progress/code/1.1a") || null)));
  step("saved code doc: " + JSON.stringify(code));
  await page.click('.lesson-foot [data-act="complete"]');
  await page.waitForTimeout(1600);
  doc = await page.evaluate(() => JSON.parse(JSON.stringify(window.__mockDocs.get("data/users/u_test/progress") || null)));
  step("lessons=" + JSON.stringify(doc.lessons) + " cards=" + Object.keys(doc.cards).length + " route=" + (await page.evaluate(() => location.hash)));
  // make a card due today, reload, review it
  await page.evaluate(() => {
    const d = JSON.parse(JSON.stringify(window.__mockDocs.get("data/users/u_test/progress")));
    const t = new Date(); const k = `${t.getFullYear()}-${String(t.getMonth() + 1).padStart(2, "0")}-${String(t.getDate()).padStart(2, "0")}`;
    d.cards["1.1#0"].due = k;
    window.__mockDocs.set("data/users/u_test/progress", d);
    localStorage.setItem("__mockdb", JSON.stringify([...window.__mockDocs]));
  });
  await page.goto(base + "index.html#review");
  await page.reload();
  await page.waitForSelector('[data-act="reveal"]', { timeout: 15000 });
  await page.click('[data-act="reveal"]');
  await page.click('[data-act="grade"][data-g="good"]');
  await page.waitForTimeout(1600);
  doc = await page.evaluate(() => JSON.parse(JSON.stringify(window.__mockDocs.get("data/users/u_test/progress"))));
  step("card after Good: " + JSON.stringify(doc.cards["1.1#0"]));
  // tutor page: chat + generate practice
  await page.goto(base + "index.html#tutor");
  await page.waitForTimeout(500);
  await page.fill("#chat-in", "What is a variable?");
  await page.press("#chat-in", "Enter");
  await page.waitForFunction(() => /closing quote/.test(document.querySelector("#chat-out").textContent), null, { timeout: 10000 });
  step("chat answered");
  await page.click('[data-act="gen"]');
  await page.waitForFunction(() => location.hash.startsWith("#p-g-"), null, { timeout: 30000 });
  await page.waitForSelector("#b-title", { timeout: 10000 });
  await page.waitForTimeout(800);
  step("practice page: " + (await page.textContent("#b-title")));
  await page.evaluate(() => document.querySelector(".CodeMirror").CodeMirror.setValue("n = int(input())\nprint('Result:', n * 2)\n"));
  await page.click('[data-act="check"]');
  await page.waitForSelector(".passed-banner", { timeout: 20000 });
  step("practice passed");
  await page.screenshot({ path: path.join(PM, "shots/12-practice.png") });
  await page.goto(base + "index.html#progress");
  await page.waitForTimeout(600);
  await page.screenshot({ path: path.join(PM, "shots/13-progress.png") });
  await page.goto(base + "index.html#today");
  await page.waitForTimeout(600);
  await page.screenshot({ path: path.join(PM, "shots/14-today-after.png") });
  console.log("logs:", logs.join("\n") || "none");
  await browser.close();
})().catch((e) => { console.error("FAILED", e); process.exit(1); });
